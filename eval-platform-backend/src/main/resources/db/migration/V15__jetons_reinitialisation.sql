-- Mot de passe oublié : liens de réinitialisation envoyés par e-mail.
-- Le jeton n'est jamais stocké : seulement son empreinte SHA-256 (une fuite de la table ne donne aucun lien valable).
-- Usage unique, 30 minutes ; une nouvelle demande invalide les précédentes. Purge horaire des lignes expirées.
create table jetons_reinitialisation (
    id bigint generated by default as identity,
    utilisateur_id bigint not null,
    empreinte varchar(64) not null,
    cree_le timestamp(6) not null,
    expire_le timestamp(6) not null,
    utilise_le timestamp(6),
    constraint pk_jetons_reinitialisation primary key (id),
    constraint uk_jetons_reinitialisation_empreinte unique (empreinte),
    constraint fk_jetons_reinitialisation_utilisateur
        foreign key (utilisateur_id) references utilisateurs (id) on delete cascade
);

-- Limite de demandes par compte (demandes des 15 dernières minutes) et invalidation des liens précédents
create index idx_jetons_reinitialisation_utilisateur on jetons_reinitialisation (utilisateur_id, cree_le);
create index idx_jetons_reinitialisation_expire_le on jetons_reinitialisation (expire_le);
