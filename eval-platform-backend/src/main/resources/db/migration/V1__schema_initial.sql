create table administrateurs (
    id bigint not null,
    primary key (id)
);

create table alertes_anti_triche (
    date_creation timestamp(6) not null,
    date_detection timestamp(6) not null,
    date_modification timestamp(6),
    enseignant_id bigint,
    id bigint generated by default as identity,
    soumission_id bigint not null,
    cree_par varchar(255),
    description varchar(255) not null,
    modifie_par varchar(255),
    niveau varchar(255) not null check (niveau in ('INFO','MODERE','ELEVE')),
    primary key (id)
);

create table amenagements_temps (
    duree_personnalisee integer not null,
    date_creation timestamp(6) not null,
    date_modification timestamp(6),
    etudiant_id bigint not null,
    evaluation_id bigint not null,
    id bigint generated by default as identity,
    cree_par varchar(255),
    modifie_par varchar(255),
    primary key (id),
    unique (etudiant_id, evaluation_id)
);

create table cas_de_tests (
    est_masque boolean not null,
    id bigint generated by default as identity,
    question_id bigint not null,
    entree TEXT,
    sortie_attendue TEXT not null,
    primary key (id)
);

create table choix_reponses (
    est_correct boolean not null,
    id bigint generated by default as identity,
    question_id bigint not null,
    texte TEXT not null,
    primary key (id)
);

create table enseignants (
    id bigint not null,
    matricule varchar(255) unique,
    primary key (id)
);

create table etudiants (
    id bigint not null,
    promotion_id bigint,
    num_etudiant varchar(255) unique,
    primary key (id)
);

create table evaluation_promotions (
    evaluation_id bigint not null,
    promotion_id bigint not null
);

create table evaluations (
    duree_standard integer not null,
    resultats_publies boolean not null,
    date_creation timestamp(6) not null,
    date_fermeture timestamp(6) not null,
    date_modification timestamp(6),
    date_ouverture timestamp(6) not null,
    enseignant_id bigint not null,
    id bigint generated by default as identity,
    cree_par varchar(255),
    description TEXT,
    modifie_par varchar(255),
    statut varchar(255) not null check (statut in ('BROUILLON','PUBLIEE','EN_COURS','TERMINEE')),
    titre varchar(255) not null,
    primary key (id)
);

create table notifications (
    lue boolean not null,
    date_envoi timestamp(6) not null,
    id bigint generated by default as identity,
    utilisateur_id bigint not null,
    message TEXT not null,
    type varchar(255) not null check (type in ('RESULTAT_PUBLIE','EVALUATION_OUVERTE','CORRECTION_VALIDEE')),
    primary key (id)
);

create table promotions (
    id bigint generated by default as identity,
    annee varchar(255) not null,
    nom varchar(255) not null,
    primary key (id)
);

create table propositions_ia (
    note_proposee float(53) not null,
    id bigint generated by default as identity,
    justification TEXT,
    statut varchar(255) not null check (statut in ('EN_ATTENTE','VALIDEE','REJETEE')),
    primary key (id)
);

create table questions (
    ordre integer not null,
    points float(53) not null,
    evaluation_id bigint not null,
    id bigint generated by default as identity,
    enonce TEXT not null,
    type varchar(255) not null check (type in ('QCM','CODE','OUVERTE','QUIZ_CHRONOMETREE')),
    primary key (id)
);

create table questions_code (
    id bigint not null,
    primary key (id)
);

create table questions_ouvertes (
    id bigint not null,
    primary key (id)
);

create table questions_qcm (
    est_choix_multiple boolean not null,
    id bigint not null,
    primary key (id)
);

create table questions_quiz (
    duree_question integer not null,
    id bigint not null,
    primary key (id)
);

create table reponse_qcm_choix (
    choix_id bigint not null,
    reponse_qcm_id bigint not null
);

create table reponses_code (
    id bigint not null,
    code_soumis TEXT,
    primary key (id)
);

create table reponses_etudiant (
    note_obtenue float(53),
    validee_par_prof boolean not null,
    date_creation timestamp(6) not null,
    date_modification timestamp(6),
    id bigint generated by default as identity,
    question_id bigint not null,
    soumission_id bigint not null,
    commentaire_prof TEXT,
    cree_par varchar(255),
    modifie_par varchar(255),
    primary key (id)
);

create table reponses_ouvertes (
    id bigint not null,
    proposition_ia_id bigint unique,
    texte_soumis TEXT,
    primary key (id)
);

create table reponses_qcm (
    id bigint not null,
    primary key (id)
);

create table resultats_cas_tests (
    est_valide boolean not null,
    temps_execution float(53) not null,
    cas_de_test_id bigint not null,
    id bigint generated by default as identity,
    reponse_code_id bigint not null,
    message_erreur TEXT,
    sortie_obtenue TEXT,
    primary key (id)
);

create table soumissions (
    nb_changements_onglet integer not null,
    note_finale float(53),
    administrateur_id bigint,
    date_creation timestamp(6) not null,
    date_debut timestamp(6) not null,
    date_modification timestamp(6),
    date_remise timestamp(6),
    etudiant_id bigint not null,
    evaluation_id bigint not null,
    id bigint generated by default as identity,
    cree_par varchar(255),
    feedback_general TEXT,
    modifie_par varchar(255),
    statut varchar(255) not null check (statut in ('EN_COURS','SOUMIS','EN_CORRECTION','EVALUE')),
    primary key (id),
    unique (evaluation_id, etudiant_id)
);

create table utilisateurs (
    actif boolean not null,
    date_creation timestamp(6) not null,
    date_modification timestamp(6),
    derniere_connexion timestamp(6),
    id bigint generated by default as identity,
    cree_par varchar(255),
    email varchar(255) not null unique,
    modifie_par varchar(255),
    mot_de_passe varchar(255) not null,
    nom varchar(255) not null,
    prenom varchar(255) not null,
    role varchar(255) not null check (role in ('ETUDIANT','ENSEIGNANT','ADMIN')),
    primary key (id)
);

