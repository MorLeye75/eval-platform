-- Révision d'une note par l'enseignant avant la publication des résultats : chaque changement est tracé.
-- Une ligne par révision (ancienne note, nouvelle note, motif, auteur, date) ; rien n'est jamais effacé.
-- Après publication, aucune note ne change plus (contrôlé par le service, sous verrou de l'évaluation).
create table revisions_note (
    id bigint generated by default as identity,
    reponse_id bigint not null,
    auteur_id bigint not null,
    ancienne_note float(53) not null,
    nouvelle_note float(53) not null,
    motif varchar(500) not null,
    revisee_le timestamp(6) not null,
    constraint pk_revisions_note primary key (id),
    constraint fk_revisions_note_reponse
        foreign key (reponse_id) references reponses_etudiant (id) on delete cascade,
    constraint fk_revisions_note_auteur
        foreign key (auteur_id) references utilisateurs (id)
);

create index idx_revisions_note_reponse on revisions_note (reponse_id, revisee_le);
